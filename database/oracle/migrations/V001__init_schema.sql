    CONSTRAINT CK_RATINGS_VERIFIED CHECK (HR_VERIFIED IN ('Y', 'N')),
    CONSTRAINT CK_RATINGS_VERIFY_DATA CHECK (
        HR_VERIFIED = 'N' OR (HR_VERIFIER_EMP_ID IS NOT NULL AND VERIFIED_AT IS NOT NULL)
    )
);

