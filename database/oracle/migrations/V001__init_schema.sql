CREATE TABLE TRAINING_COURSES (
    COURSE_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    COURSE_NAME      VARCHAR2(200) NOT NULL,
    COURSE_TYPE      VARCHAR2(50) NOT NULL,
    DURATION_HOURS   NUMBER(4,1) NOT NULL,
    TRAINER_ID       NUMBER,
    MAX_STUDENTS     NUMBER(6) NOT NULL,
    START_AT         TIMESTAMP(0),
    END_AT           TIMESTAMP(0),
    LOCATION         VARCHAR2(100),
    COURSE_STATUS    VARCHAR2(20) DEFAULT 'DRAFT' NOT NULL,
    BUDGET_AMOUNT    NUMBER(12,2) DEFAULT 0 NOT NULL,
    DEPT_ID          NUMBER,
    PRE_TEST_URL     VARCHAR2(500),
    POST_TEST_URL    VARCHAR2(500),
    MATERIAL_URL     VARCHAR2(500),
    CREATED_AT       TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TRAINING_COURSES PRIMARY KEY (COURSE_ID),
    CONSTRAINT FK_COURSES_TRAINER FOREIGN KEY (TRAINER_ID) REFERENCES TRAINERS (TRAINER_ID),
    CONSTRAINT FK_COURSES_DEPT FOREIGN KEY (DEPT_ID) REFERENCES DEPARTMENTS_TRAINING (DEPT_ID),
    CONSTRAINT UQ_COURSES_ID_TRAINER UNIQUE (COURSE_ID, TRAINER_ID),
    CONSTRAINT CK_COURSES_DURATION CHECK (DURATION_HOURS > 0),
    CONSTRAINT CK_COURSES_MAX_STUDENTS CHECK (MAX_STUDENTS > 0),
    CONSTRAINT CK_COURSES_BUDGET CHECK (BUDGET_AMOUNT >= 0),
    CONSTRAINT CK_COURSES_STATUS CHECK (COURSE_STATUS IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    CONSTRAINT CK_COURSES_TIME CHECK (END_AT IS NULL OR START_AT IS NULL OR END_AT > START_AT),
    CONSTRAINT CK_COURSES_PUBLISH_DATA CHECK (
        COURSE_STATUS = 'DRAFT' OR
        (TRAINER_ID IS NOT NULL AND DEPT_ID IS NOT NULL AND START_AT IS NOT NULL
         AND END_AT IS NOT NULL AND LOCATION IS NOT NULL)
    )
);

CREATE TABLE TRAINING_REQUESTS (
    REQUEST_ID              NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    EMP_ID                  NUMBER NOT NULL,
    COURSE_ID               NUMBER NOT NULL,
    REASON                  VARCHAR2(500) NOT NULL,
    STATUS                  VARCHAR2(20) DEFAULT 'PENDING' NOT NULL,
    DEPT_APPROVER_EMP_ID    NUMBER,
    DEPT_APPROVED_AT        TIMESTAMP(0),
    DEPT_APPROVE_REMARK     VARCHAR2(500),
    HR_FILER_EMP_ID         NUMBER,
    HR_FILED_AT             TIMESTAMP(0),
    HR_FILE_REMARK          VARCHAR2(500),
    REQUESTED_AT            TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT              TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TRAINING_REQUESTS PRIMARY KEY (REQUEST_ID),
    CONSTRAINT FK_REQUESTS_EMP FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEES (EMP_ID),
    CONSTRAINT FK_REQUESTS_COURSE FOREIGN KEY (COURSE_ID) REFERENCES TRAINING_COURSES (COURSE_ID),
    CONSTRAINT FK_REQUESTS_DEPT_APPROVER FOREIGN KEY (DEPT_APPROVER_EMP_ID) REFERENCES EMPLOYEES (EMP_ID),
    CONSTRAINT FK_REQUESTS_HR_FILER FOREIGN KEY (HR_FILER_EMP_ID) REFERENCES EMPLOYEES (EMP_ID),
    CONSTRAINT UQ_REQUESTS_ID_EMP_COURSE UNIQUE (REQUEST_ID, EMP_ID, COURSE_ID),
    CONSTRAINT CK_REQUESTS_STATUS CHECK (STATUS IN ('PENDING', 'DEPT_APPROVED', 'DEPT_REJECTED', 'HR_FILED')),
    CONSTRAINT CK_REQUESTS_HR_FILED CHECK (
        STATUS <> 'HR_FILED' OR (HR_FILER_EMP_ID IS NOT NULL AND HR_FILED_AT IS NOT NULL)
    )
);

CREATE TABLE TRAINING_REGISTRATIONS (
    REG_ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    REQUEST_ID       NUMBER NOT NULL,
    EMP_ID           NUMBER NOT NULL,
    COURSE_ID        NUMBER NOT NULL,
    STATUS           VARCHAR2(20) DEFAULT 'REGISTERED' NOT NULL,
    REGISTERED_AT    TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    COMPLETED_AT     TIMESTAMP(0),
    ACTUAL_HOURS     NUMBER(4,1),
    CANCELED_AT      TIMESTAMP(0),
    CANCEL_REASON    VARCHAR2(500),
    UPDATED_AT       TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_TRAINING_REGISTRATIONS PRIMARY KEY (REG_ID),
    CONSTRAINT FK_REG_REQUEST_EMP_COURSE FOREIGN KEY (REQUEST_ID, EMP_ID, COURSE_ID)
        REFERENCES TRAINING_REQUESTS (REQUEST_ID, EMP_ID, COURSE_ID),
    CONSTRAINT FK_REGISTRATIONS_EMP FOREIGN KEY (EMP_ID) REFERENCES EMPLOYEES (EMP_ID),
    CONSTRAINT FK_REGISTRATIONS_COURSE FOREIGN KEY (COURSE_ID) REFERENCES TRAINING_COURSES (COURSE_ID),
    CONSTRAINT CK_REGISTRATIONS_STATUS CHECK (STATUS IN ('REGISTERED', 'SIGNED_IN', 'COMPLETED', 'ABSENT', 'CANCELED')),
    CONSTRAINT CK_REGISTRATIONS_HOURS CHECK (ACTUAL_HOURS IS NULL OR ACTUAL_HOURS >= 0),
    CONSTRAINT CK_REGISTRATIONS_CANCELED CHECK (STATUS <> 'CANCELED' OR CANCELED_AT IS NOT NULL),
    CONSTRAINT CK_REGISTRATIONS_COMPLETED CHECK (
        STATUS <> 'COMPLETED' OR (COMPLETED_AT IS NOT NULL AND ACTUAL_HOURS IS NOT NULL)
    )
);

