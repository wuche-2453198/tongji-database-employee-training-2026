    UPDATED_AT       TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_EMPLOYEES PRIMARY KEY (EMP_ID),
    CONSTRAINT UQ_EMPLOYEES_LOGIN_NAME UNIQUE (LOGIN_NAME),
    CONSTRAINT UQ_EMPLOYEES_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_EMPLOYEES_DEPT FOREIGN KEY (DEPT_ID)
        REFERENCES DEPARTMENTS_TRAINING (DEPT_ID),
    CONSTRAINT FK_EMPLOYEES_MANAGER FOREIGN KEY (MANAGER_EMP_ID)
        REFERENCES EMPLOYEES (EMP_ID),
    CONSTRAINT CK_EMPLOYEES_STATUS CHECK (STATUS IN ('ACTIVE', 'RESIGNED')),
    CONSTRAINT CK_EMPLOYEES_LOGIN_LOWER CHECK (LOGIN_NAME = LOWER(LOGIN_NAME))
);

