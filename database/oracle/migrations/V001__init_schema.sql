CREATE TABLE DEPARTMENTS_TRAINING (
    DEPT_ID        NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DEPT_NAME      VARCHAR2(100) NOT NULL,
    BUDGET_YEAR    NUMBER(4) DEFAULT 2026 NOT NULL,
    ANNUAL_BUDGET  NUMBER(12,2) DEFAULT 0 NOT NULL,
    USED_BUDGET    NUMBER(12,2) DEFAULT 0 NOT NULL,
    REMAIN_BUDGET  NUMBER(12,2) GENERATED ALWAYS AS (ANNUAL_BUDGET - USED_BUDGET) VIRTUAL,
    CREATED_AT     TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT     TIMESTAMP(0) DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_DEPARTMENTS_TRAINING PRIMARY KEY (DEPT_ID),
    CONSTRAINT UQ_DEPARTMENTS_TRAINING_NAME UNIQUE (DEPT_NAME),
    CONSTRAINT CK_DEPT_BUDGET_YEAR CHECK (BUDGET_YEAR = 2026),
    CONSTRAINT CK_DEPT_ANNUAL_BUDGET CHECK (ANNUAL_BUDGET >= 0),
    CONSTRAINT CK_DEPT_USED_BUDGET CHECK (USED_BUDGET >= 0 AND USED_BUDGET <= ANNUAL_BUDGET)
);

CREATE TABLE EMPLOYEES (
    EMP_ID           NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    LOGIN_NAME       VARCHAR2(50) NOT NULL,
    PASSWORD_HASH    VARCHAR2(255) NOT NULL,
